/**
 * Repeatable seed pipeline (Phase 5).
 *
 * Reads the curated generic catalogue (catalogue-data.mjs) and (re)generates an
 * idempotent SQL migration: db/migrations/0017_seed_master_catalogue.sql.
 *
 * Idempotency:
 *  - catalogue_packs upsert on (slug)
 *  - master_products upsert on (code) — the stable business key
 *  - catalogue_pack_items insert ... on conflict do nothing
 * So applying the migration (or re-running this script) any number of times
 * converges to the same catalogue without duplicates.
 *
 * Usage: node db/seed/build-catalogue-seed.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { PACKS, expandMasterRows, slugify } from "./catalogue-data.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(
	here,
	"..",
	"migrations",
	"0017_seed_master_catalogue.sql",
);

const q = (v) =>
	v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`;

const rows = expandMasterRows();

const perCategory = {};
for (const r of rows)
	perCategory[r.category] = (perCategory[r.category] ?? 0) + 1;

const lines = [];
lines.push(
	"-- =============================================================================",
);
lines.push(
	"-- 0017_seed_master_catalogue.sql  (Phase 5 — GENERATED, do not edit by hand)",
);
lines.push("--");
lines.push(
	"-- Generated by db/seed/build-catalogue-seed.mjs from db/seed/catalogue-data.mjs.",
);
lines.push(
	"-- Idempotent: packs upsert on slug, master_products upsert on code, pack items",
);
lines.push("-- insert-on-conflict-do-nothing. Safe to re-run / re-apply.");
lines.push("--");
lines.push(
	"-- All items are GENERIC, clearly-labelled illustrative sample data: no brands,",
);
lines.push(
	"-- no fabricated MRP/GTIN/manufacturer/images. No medicines. Merchants set their",
);
lines.push(
	"-- own price/stock after import; master rows are never mutated per-merchant.",
);
lines.push("--");
lines.push(
	`-- Totals: ${rows.length} master products across ${PACKS.length} packs.`,
);
for (const [cat, n] of Object.entries(perCategory))
	lines.push(`--   • ${cat}: ${n}`);
lines.push(
	"-- =============================================================================",
);
lines.push("");

// --- packs ---
lines.push(
	"insert into public.catalogue_packs (slug, name, description, category, sort_order, is_active) values",
);
lines.push(
	PACKS.map(
		(p) =>
			`  (${q(p.slug)}, ${q(p.name)}, ${q(p.description)}, ${q(p.category)}, ${p.sortOrder}, true)`,
	).join(",\n") + "\non conflict (slug) do update set",
);
lines.push("  name = excluded.name, description = excluded.description,");
lines.push(
	"  category = excluded.category, sort_order = excluded.sort_order, is_active = true;",
);
lines.push("");

// --- master products (chunked inserts) ---
const CHUNK = 100;
for (let i = 0; i < rows.length; i += CHUNK) {
	const chunk = rows.slice(i, i + CHUNK);
	lines.push(
		"insert into public.master_products (code, name, category, subcategory, pack_size, unit, variant_label, classification, verification_status, data_source, is_active) values",
	);
	lines.push(
		chunk
			.map(
				(r) =>
					`  (${q(r.code)}, ${q(r.name)}, ${q(r.category)}, ${q(r.subcategory)}, ${q(r.packSize)}, ${q(r.unit)}, ${q(r.variantLabel)}, 'generic', 'illustrative', 'bhama_vision_sample', true)`,
			)
			.join(",\n") + "\non conflict (code) do update set",
	);
	lines.push("  name = excluded.name, category = excluded.category,");
	lines.push(
		"  subcategory = excluded.subcategory, pack_size = excluded.pack_size,",
	);
	lines.push(
		"  unit = excluded.unit, variant_label = excluded.variant_label, is_active = true;",
	);
	lines.push("");
}

// --- pack items (per pack) ---
for (const pack of PACKS) {
	const packRows = rows.filter((r) => r.packSlug === pack.slug);
	if (packRows.length === 0) continue;
	lines.push(`-- ${pack.name} (${packRows.length} items)`);
	lines.push(
		"insert into public.catalogue_pack_items (pack_id, master_product_id, position)",
	);
	lines.push(
		`select (select id from public.catalogue_packs where slug = ${q(pack.slug)}), m.id, data.position`,
	);
	lines.push("from (values");
	lines.push(
		packRows.map((r) => `  (${q(r.code)}, ${r.position})`).join(",\n"),
	);
	lines.push(") as data(code, position)");
	lines.push("join public.master_products m on m.code = data.code");
	lines.push("on conflict do nothing;");
	lines.push("");
}

writeFileSync(outFile, lines.join("\n"));

// Report
console.log(`Wrote ${outFile}`);
console.log(`Master products: ${rows.length}`);
for (const [cat, n] of Object.entries(perCategory))
	console.log(`  ${cat}: ${n}`);
